import fs from "node:fs";
import katex from "katex";
import prettier from "prettier";

const equation = String.raw`\begin{aligned}P(D\mid A)&=\frac{P(A\mid D)P(D)}{P(A)}\\[3pt]&=\frac{0{,}95\cdot0{,}02}{0{,}95\cdot0{,}02+0{,}10\cdot0{,}98}\end{aligned}`;
const result = String.raw`\frac{19}{19+98}\approx 16{,}2\%`;

const render = (tex, displayMode = false) =>
  katex.renderToString(tex, { displayMode, throwOnError: true, trust: false });

const source =
  `// Generated by scripts/generate-landing-math.mjs. Edit the TeX there.\n` +
  `export const bayesEquationHtml = ${JSON.stringify(render(equation, true))};\n` +
  `export const bayesResultHtml = ${JSON.stringify(render(result))};\n`;
fs.writeFileSync(
  new URL("../src/lib/landing-math.ts", import.meta.url),
  await prettier.format(source, { parser: "typescript" }),
);
